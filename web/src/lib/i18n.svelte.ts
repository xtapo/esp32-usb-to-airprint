class I18n {
  lang = $state<Lang>(detectLang());
  t = $derived(T[this.lang]);

  setLang(l: Lang) {
    this.lang = l;
    try {
      localStorage.setItem(STORAGE_KEY, l);
    } catch {
      /* ignore */
    }
  }

  toggle() {
    this.setLang(this.lang === 'vi' ? 'en' : 'vi');
  }
}

export const i18n = new I18n();
